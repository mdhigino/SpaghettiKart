package dev.mdhigino.mk64family;

import java.io.File;
import java.io.FileOutputStream;
import java.io.InputStream;

import android.os.Bundle;
import android.view.ViewGroup;
import android.widget.RelativeLayout;

import org.libsdl.app.SDLActivity;

/**
 * Thin wrapper around SDL's activity. SDLActivity (copied from the SDL2 source
 * tree by the CI workflow) loads the native libraries and calls SDL_main(),
 * which lives in libmain.so (the game itself).
 */
public class MainActivity extends SDLActivity {
    @Override
    protected void onCreate(Bundle savedInstanceState) {
        // Runs before the game starts, so even if the previous run crashed (or this
        // one does), the log of the previous run is saved next to the game files:
        //   Android/data/dev.mdhigino.mk64family/files/log-anterior.txt
        // This also creates that folder on the very first launch.
        saveLogOfPreviousRun();
        installBundledEngineAssets();
        super.onCreate(savedInstanceState);

        // On-screen controls, drawn over the game surface (mLayout is SDLActivity's root).
        // They need explicit full-screen size: a bare addView() would make a 0x0 view.
        // Controls are optional: a failure here must never stop the game from starting.
        try {
            if (mLayout != null) {
                mLayout.addView(new TouchControlsView(this),
                        new RelativeLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT,
                                                        ViewGroup.LayoutParams.MATCH_PARENT));
            }
        } catch (Throwable ignored) {
        }
    }

    @Override
    protected void onDestroy() {
        super.onDestroy();
        // The game runs in its own process (so the lobby can start it fresh every time):
        // make sure that process really ends, otherwise the next launch would reuse a dead engine.
        android.os.Process.killProcess(android.os.Process.myPid());
    }

    /**
     * Copies spaghetti.o2r (the port's own assets, generated by CI from the same commit
     * as the code) from the APK into the game folder. It is overwritten on every start
     * so it can never be out of sync with the app. mk64.o2r is NOT bundled: it is made
     * from the user's own ROM and copied by hand.
     */
    private void installBundledEngineAssets() {
        try {
            File dir = getExternalFilesDir(null);
            if (dir == null) {
                return;
            }
            File tmp = new File(dir, "spaghetti.o2r.tmp");
            try (InputStream in = getAssets().open("spaghetti.o2r");
                 FileOutputStream fo = new FileOutputStream(tmp)) {
                byte[] buf = new byte[65536];
                int n;
                while ((n = in.read(buf)) > 0) {
                    fo.write(buf, 0, n);
                }
            }
            File out = new File(dir, "spaghetti.o2r");
            if (out.exists()) {
                out.delete();
            }
            tmp.renameTo(out);
        } catch (Throwable ignored) {
            // Not bundled (or storage not ready): the game then uses whatever file is there.
        }
    }

    private void saveLogOfPreviousRun() {
        try {
            File dir = getExternalFilesDir(null);
            if (dir == null) {
                return;
            }
            File out = new File(dir, "log-anterior.txt");
            // An app can read its own log entries (not other apps').
            Process p = Runtime.getRuntime().exec(new String[] { "logcat", "-d", "-v", "time" });
            try (InputStream in = p.getInputStream(); FileOutputStream fo = new FileOutputStream(out)) {
                byte[] buf = new byte[8192];
                int n;
                while ((n = in.read(buf)) > 0) {
                    fo.write(buf, 0, n);
                }
            }
            p.waitFor();
        } catch (Throwable ignored) {
            // Logging must never be the reason the app fails to start.
        }
    }

    @Override
    protected String[] getLibraries() {
        // SDL's HIDAPI support ships as a separate libhidapi.so on Android.
        // Only ask for it if the build produced it.
        File dir = new File(getApplicationInfo().nativeLibraryDir);
        if (new File(dir, "libhidapi.so").exists()) {
            return new String[] { "hidapi", "SDL2", "main" };
        }
        return new String[] { "SDL2", "main" };
    }
}
